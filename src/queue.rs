    pub fn new(spotify: Spotify, cfg: Arc<Config>, library: Arc<Library>) -> Self {
        let queue_state = cfg.state().queuestate.clone();
        let queue_len = queue_state.queue.len();
        let current_track = queue_state.current_track.filter(|index| *index < queue_len);
        let random_order = queue_state.random_order.and_then(|mut order| {
            let mut seen = HashSet::new();
            order.retain(|index| *index < queue_len && seen.insert(*index));
            (order.len() == queue_len).then_some(order)
        });
        let explicit_queued = queue_state
            .explicit_queued
            .into_iter()
            .filter(|index| *index < queue_len)
            .collect();
        let radio_generated = queue_state
            .radio_generated
            .into_iter()
            .filter(|index| *index < queue_len)
            .collect();
        let resume_context: Vec<usize> = queue_state
            .resume_context
            .into_iter()
            .filter(|index| *index < queue_len)
            .collect();
        let resume_context_valid = queue_state.resume_context_valid || !resume_context.is_empty();

        Self {
            queue: Arc::new(RwLock::new(queue_state.queue)),
            spotify: spotify.clone(),
            current_track: RwLock::new(current_track),
            random_order: RwLock::new(random_order),
            cfg,
            library,
            listening: Mutex::new(crate::recommendations::tracker::Tracker::new(
                crate::recommendations::history::shared(),
            )),
            session_played: Mutex::new(HashSet::new()),
            session_song_keys: Mutex::new(HashSet::new()),
            explicit_queued: RwLock::new(explicit_queued),
            radio_generated: RwLock::new(radio_generated),
            active_radio: RwLock::new(HashSet::new()),
            rpc_mutation: Mutex::new(0),
            played_indices: RwLock::new(HashSet::new()),
            current_token: RwLock::new(0),
            resume_context: RwLock::new(resume_context),
            resume_context_valid: RwLock::new(resume_context_valid),
            radio: Mutex::new(RadioState::default()),
        }
    }

    fn current_play_position_locked(
        current: Option<usize>,
        random_order: Option<&Vec<usize>>,
        queue_len: usize,
    ) -> Option<usize> {
        current.and_then(|index| {
            random_order
                .and_then(|order| order.iter().position(|&item| item == index))
                .or_else(|| current.filter(|&index| index < queue_len))
        })
    }

    fn play_index_at_locked(
        random_order: Option<&Vec<usize>>,
        position: usize,
        queue_len: usize,
    ) -> Option<usize> {
        let index = match random_order {
            Some(order) => *order.get(position)?,
            None => position,
        };
        (index < queue_len).then_some(index)
    }

    #[allow(clippy::too_many_arguments)]
    fn upcoming_indices_locked(
        &self,
        count: usize,
        current: Option<usize>,
        random_order: Option<&Vec<usize>>,
        queue_len: usize,
        played: &HashSet<usize>,
        explicit: &HashSet<usize>,
        active_radio: &HashSet<usize>,
        radio_generated: &HashSet<usize>,
        resume_context: &[usize],
        resume_context_valid: bool,
        auto_excluded: &HashSet<usize>,
        radio_active: bool,
    ) -> Vec<usize> {
        let order_len = random_order.map_or(queue_len, Vec::len);
        if order_len == 0 {
            return Vec::new();
        }
        let current_position = Self::current_play_position_locked(current, random_order, queue_len);
        let cyclic_position = |offset: usize| {
            current_position
                .map(|position| (position + 1 + offset) % order_len)
                .unwrap_or(offset)
        };
        if !radio_active {
            if !resume_context_valid {
                let start = current_position.map_or(0, |position| position + 1);
                return (start..order_len)
                    .filter_map(|position| {
                        Self::play_index_at_locked(random_order, position, queue_len)
                    })
                    .filter(|index| {
                        !(played.contains(index) && radio_generated.contains(index))
                            && !auto_excluded.contains(index)
                    })
                    .take(count)
                    .collect();
            }
            let mut upcoming = Vec::new();
            let mut seen = HashSet::new();
            // Explicit entries are user choices and retain priority after a
            // station is stopped, including when they were appended behind a
            // raw radio tail.
            for offset in 0..order_len {
                let position = cyclic_position(offset);
                let Some(index) = Self::play_index_at_locked(random_order, position, queue_len)
                else {
                    continue;
                };
                if explicit.contains(&index)
                    && Some(index) != current
                    && !played.contains(&index)
                    && seen.insert(index)
                {
                    upcoming.push(index);
                    if upcoming.len() == count {
                        return upcoming;
                    }
                }
            }
            // Context that was parked at station start may now lie before the
            // current automatic item in the raw vector. Preserve its original
            // order so stopping radio resumes that context.
            for index in resume_context {
                if *index < queue_len
                    && Some(*index) != current
                    && !played.contains(index)
                    && !radio_generated.contains(index)
                    && seen.insert(*index)
                {
                    upcoming.push(*index);
                    if upcoming.len() == count {
                        return upcoming;
                    }
                }
            }
            // Finally expose ordinary future raw entries. Generated entries
            // from the abandoned station stay parked after cancellation.
            let start = current_position.map_or(0, |position| position + 1);
            for position in start..order_len {
                let Some(index) = Self::play_index_at_locked(random_order, position, queue_len)
                else {
                    continue;
                };
                if !radio_generated.contains(&index)
                    && !auto_excluded.contains(&index)
                    && seen.insert(index)
                {
                    upcoming.push(index);
                    if upcoming.len() == count {
                        return upcoming;
                    }
                }
            }
            return upcoming;
        }

        let mut upcoming = Vec::new();
        // Explicit and current-generation radio entries are station lanes. Walk
        // the whole playback order cyclically: a manual item at the raw tail
        // may become current before automatic items that were inserted earlier.
        for (lane, automatic) in [(explicit, false), (active_radio, true)] {
            let mut seen = HashSet::new();
            for offset in 0..order_len {
                let position = cyclic_position(offset);
                let Some(index) = Self::play_index_at_locked(random_order, position, queue_len)
                else {
                    continue;
                };
                if lane.contains(&index)
                    && Some(index) != current
                    && !played.contains(&index)
                    && (!automatic || !auto_excluded.contains(&index))
                    && seen.insert(index)
                {
                    upcoming.push(index);
                    if upcoming.len() == count {
                        return upcoming;
                    }
                }
            }
        }
        upcoming
    }

    /// Return future entries in the effective playback lane. During radio,
    /// unplayed explicit entries come first, followed by the current station's
    /// automatic entries; restored and older-station context is parked.
    pub fn upcoming(&self, count: usize) -> Vec<(usize, Playable)> {
        if count == 0 {
            return Vec::new();
        }
        let radio = self.radio.lock().unwrap();
        let radio_active = radio.active;
        let random_order = self.random_order.read().unwrap();
        let queue = self.queue.read().unwrap();
        let current = *self.current_track.read().unwrap();
        let played = self.played_indices.read().unwrap();
        let explicit = self.explicit_queued.read().unwrap();
        let active_radio = self.active_radio.read().unwrap();
        let radio_generated = self.radio_generated.read().unwrap();
        let resume_context = self.resume_context.read().unwrap();
        let resume_context_valid = *self.resume_context_valid.read().unwrap();
        let session_played = self.session_played.lock().unwrap();
        let session_song_keys = self.session_song_keys.lock().unwrap();
        let auto_excluded = automatic_session_excluded(
            &queue,
            &radio_generated,
            &session_played,
            &session_song_keys,
        );
        let indices = self.upcoming_indices_locked(
            count,
            current,
            random_order.as_ref(),
            queue.len(),
            &played,
            &explicit,
            &active_radio,
            &radio_generated,
            &resume_context,
            resume_context_valid,
            &auto_excluded,
            radio_active,
        );
        drop(radio);
        indices
            .into_iter()
            .filter_map(|index| queue.get(index).cloned().map(|item| (index, item)))
            .collect()
    }

    /// The index of the next item in `self.queue` that should be played. None
    /// if the active station has no eligible lane entries or the queue is at
    /// its end.
    pub fn next_index(&self) -> Option<usize> {
        self.get_current_index()?;
        self.upcoming(1).into_iter().next().map(|(index, _)| index)
    }

    /// The index of the previous item in `self.queue` that should be played.
    /// None if at the start of the queue.
    pub fn previous_index(&self) -> Option<usize> {
        // Copy and release before taking shuffle order: edits acquire order before current.
        let current = self.get_current_index();
        match current {
            Some(mut index) => {
                let random_order = self.random_order.read().unwrap();
                if let Some(order) = random_order.as_ref() {
                    index = order.iter().position(|&i| i == index)?;
                }

                if index > 0 {
                    let mut next_index = index - 1;
                    if let Some(order) = random_order.as_ref() {
                        next_index = order[next_index];
                    }

                    Some(next_index)
                } else {
                    None
                }
            }
            None => None,
        }
    }

    /// Up to `count` items in the order they will play, starting `start` places into
    /// that order, each with its index in `self.queue`.
    pub fn in_play_order(&self, start: usize, count: usize) -> Vec<(usize, Playable)> {
        let random_order = self.random_order.read().unwrap();
        let queue = self.queue.read().unwrap();
        (start..queue.len().min(start.saturating_add(count)))
            .filter_map(|position| {
                let index = match random_order.as_ref() {
                    Some(order) => *order.get(position)?,
                    None => position,
                };
                Some((index, queue.get(index)?.clone()))
            })
            .collect()
    }

    /// Where the item at `index` in `self.queue` falls in the order the queue plays.
    pub fn play_position(&self, index: usize) -> Option<usize> {
        match self.random_order.read().unwrap().as_ref() {
            Some(order) => order.iter().position(|&i| i == index),
            None => Some(index),
        }
    }

    /// The currently playing item from `self.queue`.
    pub fn get_current(&self) -> Option<Playable> {
        self.get_current_index()
            .and_then(|index| self.queue.read().unwrap().get(index).cloned())
    }

    /// The index of the currently playing item from `self.queue`.
    pub fn get_current_index(&self) -> Option<usize> {
        *self.current_track.read().unwrap()
    }

    pub fn get_library(&self) -> Arc<Library> {
        self.library.clone()
    }

    /// Return the URI set accumulated by this terminal session.
    ///
    /// This is a snapshot so recommendation workers can hold it without
    /// keeping the queue lock. Queue edits never clear the set.
    pub fn session_played(&self) -> HashSet<String> {
        self.session_played.lock().unwrap().clone()
    }

    fn mark_session_played(&self, uri: String) {
        self.session_played.lock().unwrap().insert(uri);
    }

    /// Return canonical song identities observed in this terminal session.
    /// Queue edits never clear this set.
    pub fn session_played_song_keys(&self) -> HashSet<String> {
        self.session_song_keys.lock().unwrap().clone()
    }

    fn mark_session_played_track(&self, track: &Track) {
        self.mark_session_played(track.uri.clone());
        let key = crate::recommendations::engine::song_key(track);
        if !key.is_empty() {
            self.session_song_keys.lock().unwrap().insert(key);
        }
    }

    fn mark_session_played_item(&self, item: &Playable) {
        if let Some(track) = item.track() {
            self.mark_session_played_track(&track);
        } else {
            self.mark_session_played(item.uri());
        }
    }

    /// Return exact per-occurrence provenance for persistence. Indices are
    /// already maintained under queue edits; sorting makes state output stable.
    pub fn queue_provenance(&self) -> (Vec<usize>, Vec<usize>) {
        let mut explicit: Vec<_> = self
            .explicit_queued
            .read()
            .unwrap()
            .iter()
            .copied()
            .collect();
        let mut radio: Vec<_> = self
            .radio_generated
            .read()
            .unwrap()
            .iter()
            .copied()
            .collect();
        explicit.sort_unstable();
        radio.sort_unstable();
        (explicit, radio)
    }

    /// Snapshot the parked continuation so shutdown persistence can preserve a
    /// station's original context even after playback reaches a raw radio tail.
    pub fn resume_context(&self) -> Vec<usize> {
        self.resume_context.read().unwrap().clone()
    }

    pub fn queue_resume_context(&self) -> Vec<usize> {
        self.resume_context()
    }

    pub fn queue_resume_context_valid(&self) -> bool {
        *self.resume_context_valid.read().unwrap()
    }

    pub(crate) fn radio_seed_track(&self) -> Option<Track> {
        self.radio.lock().unwrap().seed_track.clone()
    }

    /// Return the URI set that actually reserves songs for the current radio
    /// request. Parked context and past entries are intentionally omitted.
    pub fn recommendation_queued(&self) -> HashSet<String> {
        let radio = self.radio.lock().unwrap();
        let random_order = self.random_order.read().unwrap();
        let queue = self.queue.read().unwrap();
        let current = *self.current_track.read().unwrap();
        let played = self.played_indices.read().unwrap();
        let explicit = self.explicit_queued.read().unwrap();
        let active_radio = self.active_radio.read().unwrap();
        let radio_generated = self.radio_generated.read().unwrap();
        let resume_context = self.resume_context.read().unwrap();
        let resume_context_valid = *self.resume_context_valid.read().unwrap();
        let session_played = self.session_played.lock().unwrap();
        let session_song_keys = self.session_song_keys.lock().unwrap();
        let auto_excluded = automatic_session_excluded(
            &queue,
            &radio_generated,
            &session_played,
            &session_song_keys,
        );
        let mut queued = HashSet::new();
        if let Some(index) = current
            && let Some(item) = queue.get(index)
        {
            queued.insert(item.uri());
        }
        let indices = self.upcoming_indices_locked(
            usize::MAX,
            current,
            random_order.as_ref(),
            queue.len(),
            &played,
            &explicit,
            &active_radio,
            &radio_generated,
            &resume_context,
            resume_context_valid,
            &auto_excluded,
            radio.active,
        );
        drop(radio);
        for index in indices {
            if let Some(item) = queue.get(index) {
                queued.insert(item.uri());
            }
        }
        queued
    }

    pub fn queue_origin(&self, index: usize) -> &'static str {
        if self.explicit_queued.read().unwrap().contains(&index) {
            "explicit"
        } else if self.radio_generated.read().unwrap().contains(&index) {
            "radio"
        } else {
            "context"
        }
    }

    /// Count future entries parked behind the active radio lane. Historical
    /// radio entries are included because they are not active in this station.
    pub fn parked_context_count(&self) -> usize {
        let radio = self.radio.lock().unwrap();
        if !radio.active {
            return 0;
        }
        let random_order = self.random_order.read().unwrap();
        let queue = self.queue.read().unwrap();
        let current = *self.current_track.read().unwrap();
        let played = self.played_indices.read().unwrap();
        let explicit = self.explicit_queued.read().unwrap();
        let active_radio = self.active_radio.read().unwrap();
        let radio_generated = self.radio_generated.read().unwrap();
        let resume_context = self.resume_context.read().unwrap();
        let session_played = self.session_played.lock().unwrap();
        let session_song_keys = self.session_song_keys.lock().unwrap();
        let auto_excluded = automatic_session_excluded(
            &queue,
            &radio_generated,
            &session_played,
            &session_song_keys,
        );
        let Some(current_position) =
            Self::current_play_position_locked(current, random_order.as_ref(), queue.len())
        else {
            return 0;
        };
        let order_len = random_order.as_ref().map_or(queue.len(), Vec::len);
        let mut parked = HashSet::new();
        if !resume_context.is_empty() {
            parked.extend(resume_context.iter().copied().filter(|index| {
                *index < queue.len()
                    && !played.contains(index)
                    && !explicit.contains(index)
                    && !active_radio.contains(index)
                    && !radio_generated.contains(index)
                    && !auto_excluded.contains(index)
            }));
        }
        parked.extend(
            ((current_position + 1)..order_len)
                .filter_map(|position| {
                    Self::play_index_at_locked(random_order.as_ref(), position, queue.len())
                })
                .filter(|index| {
                    !played.contains(index)
                        && !explicit.contains(index)
                        && !active_radio.contains(index)
                        && !radio_generated.contains(index)
                        && !auto_excluded.contains(index)
                }),
        );
        parked.len()
    }

    /// Begin a new radio station anchored to the supplied track metadata.
    /// Starting another station invalidates delayed workers and parks older
    /// automatic entries without deleting any raw queue item.
    pub fn start_radio_track(&self, track: &Track) -> u64 {
        let _mutation = self.rpc_mutation.lock().unwrap();
        self.start_radio_track_locked(track)
    }

    fn start_radio_track_locked(&self, track: &Track) -> u64 {
        let mut radio = self.radio.lock().unwrap();
        let random_order = self.random_order.read().unwrap();
        let queue = self.queue.read().unwrap();
        let current_index = *self.current_track.read().unwrap();
        let current_position =
            Self::current_play_position_locked(current_index, random_order.as_ref(), queue.len());
        let explicit = self.explicit_queued.read().unwrap().clone();
        let played = self.played_indices.read().unwrap().clone();
        let radio_generated = self.radio_generated.read().unwrap().clone();
        let session_played = self.session_played.lock().unwrap().clone();
        let session_song_keys = self.session_song_keys.lock().unwrap().clone();
        let auto_excluded = automatic_session_excluded(
            &queue,
            &radio_generated,
            &session_played,
            &session_song_keys,
        );
        let existing_resume = self.resume_context.read().unwrap().clone();
        let existing_resume_valid = *self.resume_context_valid.read().unwrap();
        let order_len = random_order.as_ref().map_or(queue.len(), Vec::len);
        let parked = if existing_resume_valid {
            existing_resume
                .into_iter()
                .filter(|index| !auto_excluded.contains(index))
                .collect::<Vec<_>>()
        } else {
            current_position
                .map(|position| {
                    ((position + 1)..order_len)
                        .filter_map(|position| {
                            Self::play_index_at_locked(random_order.as_ref(), position, queue.len())
                        })
                        .filter(|index| {
                            Some(*index) != current_index
                                && !played.contains(index)
                                && !explicit.contains(index)
                                && !radio_generated.contains(index)
                                && !auto_excluded.contains(index)
                        })
                        .collect::<Vec<_>>()
                })
                .unwrap_or_default()
        };
        let past_explicit = if existing_resume_valid {
            Vec::new()
        } else {
            current_position
                .map(|position| {
                    (0..=position)
                        .filter_map(|position| {
                            Self::play_index_at_locked(random_order.as_ref(), position, queue.len())
                        })
                        .filter(|index| explicit.contains(index))
                        .collect::<Vec<_>>()
                })
                .unwrap_or_default()
        };
        drop(played);
        drop(explicit);
        drop(queue);
        drop(random_order);
        {
            let mut played = self.played_indices.write().unwrap();
            if let Some(index) = current_index {
                played.insert(index);
            }
            played.extend(past_explicit);
        }
        if let Some(index) = current_index {
            self.resume_context
                .write()
                .unwrap()
                .retain(|pending| *pending != index);
        }
        *self.resume_context.write().unwrap() = parked;
        *self.resume_context_valid.write().unwrap() = true;
        self.mark_session_played_track(track);
        self.active_radio.write().unwrap().clear();
        radio.generation = radio.generation.wrapping_add(1).max(1);
        radio.active = true;
        radio.seed = Some(track.uri.clone());
        radio.seed_track = Some(track.clone());
        radio.in_flight = false;
        radio.retry_at = None;
        radio.retry_attempt = 0;
        radio.waiting = false;
        radio.natural_end = false;
        radio.refresh_requested = false;
        radio.generation
    }

    /// Compatibility entry point for tests and older callers. Production UI
    /// paths should pass the fully resolved seed track to `start_radio_track`.
    pub fn start_radio(&self, seed: &str) -> u64 {
        let track = self
            .get_current()
            .and_then(|item| item.track().filter(|track| track.uri == seed))
            .or_else(|| {
                self.queue
                    .read()
                    .unwrap()
                    .iter()
                    .find_map(|item| item.track().filter(|track| track.uri == seed))
            })
            .or_else(|| {
                self.library
                    .tracks
                    .read()
                    .unwrap()
                    .iter()
                    .find(|track| track.uri == seed)
                    .cloned()
            });
        if let Some(track) = track {
            return self.start_radio_track(&track);
        }

        let _mutation = self.rpc_mutation.lock().unwrap();
        let mut radio = self.radio.lock().unwrap();
        *self.resume_context.write().unwrap() = Vec::new();
        *self.resume_context_valid.write().unwrap() = false;
        self.active_radio.write().unwrap().clear();
        radio.generation = radio.generation.wrapping_add(1).max(1);
        radio.active = true;
        radio.seed = Some(seed.to_owned());
        radio.seed_track = None;
        radio.in_flight = false;
        radio.retry_at = None;
        radio.retry_attempt = 0;
        radio.waiting = false;
        radio.natural_end = false;
        radio.refresh_requested = false;
        radio.generation
    }

    /// Cancel the current station and invalidate every delayed fill.
    pub fn cancel_radio(&self) {
        let mut radio = self.radio.lock().unwrap();
        radio.generation = radio.generation.wrapping_add(1).max(1);
        radio.active = false;
        radio.seed = None;
        radio.seed_track = None;
        radio.in_flight = false;
        radio.retry_at = None;
        radio.retry_attempt = 0;
        radio.waiting = false;
        radio.natural_end = false;
        radio.refresh_requested = false;
        self.active_radio.write().unwrap().clear();
    }

    pub(crate) fn radio_active(&self) -> bool {
        self.radio.lock().unwrap().active
    }

    pub(crate) fn radio_seed(&self) -> Option<String> {
        self.radio.lock().unwrap().seed.clone()
    }

    /// Whether a station is deliberately waiting for more metadata. A natural
    /// queue exhaustion keeps this state alive; playback failures cancel it from
    /// the application event loop instead.
    pub(crate) fn radio_waiting(&self) -> bool {
        let radio = self.radio.lock().unwrap();
        radio.active && (radio.waiting || radio.natural_end)
    }

    pub(crate) fn radio_natural_end(&self) -> bool {
        let radio = self.radio.lock().unwrap();
        radio.active && radio.natural_end
    }

    fn wait_for_radio_or_stop(&self) {
        if self.radio_active() {
            self.radio.lock().unwrap().natural_end = true;
            // EndOfTrack already silenced the player. Avoid manufacturing a
            // Stopped event that could be confused with a playback failure.
            // A manual skip at the end pauses the outgoing song while waiting.
            if matches!(self.spotify.get_current_status(), PlayerEvent::Playing(_)) {
                self.spotify.pause();
            }
        } else {
            self.spotify.stop();
        }
    }

    /// Resume on the UI thread after a batch arrives, including a batch that
    /// was already in flight when the queue reached its end.
    pub(crate) fn resume_radio_if_ready(&self) -> bool {
        let _mutation = self.rpc_mutation.lock().unwrap();
        if !self.radio_natural_end() {
            return false;
        }
        let Some(index) = self.next_index() else {
            return false;
        };
        self.play(index, false, false);
        true
    }

    /// Claim one station fill. `force` is used only for a freshly started
    /// station; normal maintenance waits until the active lane has reached its
    /// low-water mark. The claim carries the original station seed and exact
    /// current queue occurrence so a delayed result cannot drift stations.
    pub(crate) fn radio_begin_fill(&self, force: bool, low_water: usize) -> Option<RadioFill> {
        let mut radio = self.radio.lock().unwrap();
        if !radio.active || radio.in_flight {
            return None;
        }
        if !force
            && radio
                .retry_at
                .is_some_and(|retry_at| Instant::now() < retry_at)
        {
            return None;
        }

        let random_order = self.random_order.read().unwrap();
        let queue = self.queue.read().unwrap();
        let current = *self.current_track.read().unwrap();
        let played = self.played_indices.read().unwrap();
        let explicit = self.explicit_queued.read().unwrap();
        let active_radio = self.active_radio.read().unwrap();
        let radio_generated = self.radio_generated.read().unwrap();
        let resume_context = self.resume_context.read().unwrap();
        let resume_context_valid = *self.resume_context_valid.read().unwrap();
        let session_played = self.session_played.lock().unwrap();
        let session_song_keys = self.session_song_keys.lock().unwrap();
        let auto_excluded = automatic_session_excluded(
            &queue,
            &radio_generated,
            &session_played,
            &session_song_keys,
        );
        let upcoming = self.upcoming_indices_locked(
            usize::MAX,
            current,
            random_order.as_ref(),
            queue.len(),
            &played,
            &explicit,
            &active_radio,
            &radio_generated,
            &resume_context,
            resume_context_valid,
            &auto_excluded,
            true,
        );
        let automatic_upcoming = upcoming
            .iter()
            .filter(|index| active_radio.contains(index))
            .count();
        if !force && automatic_upcoming > low_water {
            return None;
        }
        let current_index = current.filter(|index| queue.get(*index).is_some())?;
        let current_uri = queue.get(current_index)?.uri();
        let current_token = *self.current_token.read().unwrap();
        let seed = radio
            .seed_track
            .clone()
            .or_else(|| queue.get(current_index).and_then(|item| item.track()))?;

        radio.in_flight = true;
        radio.waiting = false;
        Some(RadioFill {
            generation: radio.generation,
            seed,
            current_index,
            current_uri,
            current_token,
        })
    }

    /// Complete a claimed fill. A zero-sized batch gets exponential backoff so
    /// an empty or finite local catalogue cannot produce a request storm.
    pub(crate) fn radio_finish_fill(&self, generation: u64, added: usize) -> bool {
        let mut radio = self.radio.lock().unwrap();
        if !radio.active || radio.generation != generation {
            return false;
        }
        radio.in_flight = false;
        if added > 0 {
            radio.retry_at = None;
            radio.retry_attempt = 0;
            radio.waiting = false;
        } else {
            radio.retry_attempt = radio.retry_attempt.saturating_add(1);
            let shift = u32::from(radio.retry_attempt.saturating_sub(1).min(6));
            let delay = RADIO_RETRY_BASE
                .checked_mul(1_u32 << shift)
                .unwrap_or(RADIO_RETRY_MAX)
                .min(RADIO_RETRY_MAX);
            radio.retry_at = Some(Instant::now() + delay);
            radio.waiting = true;
        }
        true
    }

    /// Wake a station after enrichment or another metadata update. This only
    /// changes the retry deadline; the single-flight guard still owns spawning.
    pub(crate) fn radio_wake(&self, generation: u64) {
        let mut radio = self.radio.lock().unwrap();
        if radio.active && radio.generation == generation && !radio.in_flight {
            radio.retry_at = Some(Instant::now());
        }
    }

    pub(crate) fn radio_retry_delay(&self, generation: u64) -> Option<Duration> {
        let radio = self.radio.lock().unwrap();
        if !radio.active || radio.generation != generation {
            return None;
        }
        radio
            .retry_at
            .map(|deadline| deadline.saturating_duration_since(Instant::now()))
    }

    /// Request at most one enrichment refresh for a station lifetime.
    pub(crate) fn radio_take_refresh(&self, generation: u64) -> bool {
        let mut radio = self.radio.lock().unwrap();
        if !radio.active || radio.generation != generation || radio.refresh_requested {
            return false;
        }
        radio.refresh_requested = true;
        true
    }

    fn radio_is_current_locked(&self, radio: &RadioState, generation: u64) -> bool {
        radio.active && radio.generation == generation
    }

    fn is_radio_generated(&self, index: usize) -> bool {
        self.radio_generated.read().unwrap().contains(&index)
    }

    pub fn observe_listening(&self) {
        let playing = matches!(self.spotify.get_current_status(), PlayerEvent::Playing(_));
        let track = {
            // Snapshot and mark one exact occurrence under the same lock order
            // used by structural radio edits. The tracker callback runs after
            // releasing the queue locks so it cannot observe a half-updated
            // queue while another player event arrives.
            let _radio = self.radio.lock().unwrap();
            let queue = self.queue.read().unwrap();
            let current = *self.current_track.read().unwrap();
            let current_item = current.and_then(|index| queue.get(index).cloned());
            if playing {
                if let Some(item) = &current_item {
                    self.mark_session_played_item(item);
                }
                if let Some(index) = current {
                    self.played_indices.write().unwrap().insert(index);
                    self.resume_context
                        .write()
                        .unwrap()
                        .retain(|pending| *pending != index);
                }
            }
            current_item.as_ref().and_then(|item| item.track())
        };
        self.listening.lock().unwrap().observe(track, playing);
    }

    pub fn finish_listening(&self) {
        self.observe_listening();
        self.listening.lock().unwrap().finish(false, false);
    }

    /// Insert `track` as the item that should logically follow the currently
    /// playing item, taking into account shuffle status.
    pub fn insert_after_current(&self, track: Playable) {
        let mut generation = self.rpc_mutation.lock().unwrap();
        self.insert_after_current_inner(track);
        *generation = generation.wrapping_add(1);
    }

    fn insert_after_current_inner(&self, track: Playable) {
        if let Some(index) = self.get_current_index() {
            let mut random_order = self.random_order.write().unwrap();
            if let Some(order) = random_order.as_mut() {
                let next_i = order.iter().position(|&i| i == index).unwrap();
                // shift everything after the insertion in order
                for item in order.iter_mut() {
                    if *item > index {
                        *item += 1;
                    }
                }
                // finally, add the next track index
                order.insert(next_i + 1, index + 1);
            }
            let mut q = self.queue.write().unwrap();
            q.insert(index + 1, track);
            let inserted = index + 1;
            shift_indices_on_insert(&mut self.explicit_queued.write().unwrap(), inserted, 1);
            self.explicit_queued.write().unwrap().insert(inserted);
            shift_indices_on_insert(&mut self.radio_generated.write().unwrap(), index + 1, 1);
            shift_indices_on_insert(&mut self.active_radio.write().unwrap(), inserted, 1);
            shift_indices_on_insert(&mut self.played_indices.write().unwrap(), index + 1, 1);
            shift_resume_on_insert(&mut self.resume_context.write().unwrap(), inserted, 1);
        } else {
            self.append_inner(track);
        }
    }

    /// Add `track` to the end of the queue.
    pub fn append(&self, track: Playable) {
        let mut generation = self.rpc_mutation.lock().unwrap();
        self.append_inner(track);
        *generation = generation.wrapping_add(1);
    }

    fn append_inner(&self, track: Playable) {
        self.append_item_inner(track, true);
    }

    /// Append an item that belongs to a loaded playback context. Context
    /// entries stay unmarked so an active radio station can park and resume
    /// them instead of treating every playlist tail as a manual priority.
    fn append_context_inner(&self, track: Playable) {
        self.append_item_inner(track, false);
    }

    fn append_item_inner(&self, track: Playable, explicit: bool) {
        let mut random_order = self.random_order.write().unwrap();
        if let Some(order) = random_order.as_mut() {
            order.push(order.len());
        }

        let mut q = self.queue.write().unwrap();
        let index = q.len();
        q.push(track);
        if explicit {
            self.explicit_queued.write().unwrap().insert(index);
        }
    }

    /// Append `tracks` after the currently playing item, taking into account
    /// shuffle status. Returns the first index(in `self.queue`) of added items.
    pub fn append_next(&self, tracks: &[Playable]) -> usize {
        self.append_next_checked(None, tracks).unwrap().0
    }

    /// Compare the seed and insert under the same locks. A delayed radio worker
    /// must never splice its songs behind a track the user switched to.
    pub fn append_next_if_current(&self, seed: &str, tracks: &[Playable]) -> Option<usize> {
        self.append_next_checked(Some(seed), tracks)
            .map(|(_, count)| count)
    }

    /// Insert a radio batch immediately after the current item. The station
