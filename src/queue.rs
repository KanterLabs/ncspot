    fn append_next_checked(
        &self,
        seed: Option<&str>,
        tracks: &[Playable],
    ) -> Option<(usize, usize)> {
        let mut generation_guard = self.rpc_mutation.lock().unwrap();
        *generation_guard = generation_guard.wrapping_add(1);
        let mut random_order = self.random_order.write().unwrap();
        let mut q = self.queue.write().unwrap();

        let current = *self.current_track.read().unwrap();
        if let Some(seed) = seed
            && !current
                .and_then(|index| q.get(index))
                .is_some_and(|track| track.uri() == seed)
        {
            return None;
        }
        let filtered;
        let tracks = if seed.is_some() {
            let mut known: std::collections::HashSet<_> = q.iter().map(Playable::uri).collect();
            filtered = tracks
                .iter()
                .filter(|track| known.insert(track.uri()))
                .cloned()
                .collect::<Vec<_>>();
            filtered.as_slice()
        } else {
            tracks
        };
        let first = match current {
            Some(index) => index + 1,
            None => q.len(),
        };

        if !tracks.is_empty() {
            if let Some(order) = random_order.as_mut() {
                let insertion_position = current
                    .and_then(|index| order.iter().position(|&item| item == index))
                    .map_or(order.len(), |position| position + 1);

                // Inserting into the raw queue shifts every existing item at or
                // after `first`; update their shuffle indices before adding the
                // new indices immediately after the current play position.
                for index in order.iter_mut() {
                    if *index >= first {
                        *index += tracks.len();
                    }
                }
                order.splice(
                    insertion_position..insertion_position,
                    first..first + tracks.len(),
                );
            }

            shift_indices_on_insert(
                &mut self.explicit_queued.write().unwrap(),
                first,
                tracks.len(),
            );
            shift_indices_on_insert(
                &mut self.radio_generated.write().unwrap(),
                first,
                tracks.len(),
            );
            shift_indices_on_insert(&mut self.active_radio.write().unwrap(), first, tracks.len());
            shift_indices_on_insert(
                &mut self.played_indices.write().unwrap(),
                first,
                tracks.len(),
            );
            shift_resume_on_insert(
                &mut self.resume_context.write().unwrap(),
                first,
                tracks.len(),
            );

            for (i, track) in (first..).zip(tracks.iter()) {
                q.insert(i, track.clone());
            }
            if seed.is_none() {
                let mut explicit = self.explicit_queued.write().unwrap();
                explicit.extend(first..first + tracks.len());
            }
        }

        Some((first, tracks.len()))
    }

    #[allow(clippy::too_many_arguments)]
    fn append_radio_checked(
        &self,
        generation: u64,
        expected_index: Option<usize>,
        expected_token: Option<u64>,
        current_uri: &str,
        station_seed: Option<&Track>,
        tracks: &[Playable],
        after_current: bool,
    ) -> Option<usize> {
        let mut generation_guard = self.rpc_mutation.lock().unwrap();
        let radio = self.radio.lock().unwrap();
        if !self.radio_is_current_locked(&radio, generation) {
            return None;
        }
        let mut random_order = self.random_order.write().unwrap();
        let mut q = self.queue.write().unwrap();

        let current = *self.current_track.read().unwrap();
        if expected_index.is_some_and(|index| current != Some(index)) {
            return None;
        }
        if expected_token.is_some_and(|token| *self.current_token.read().unwrap() != token) {
            return None;
        }

        let current_item = current.and_then(|index| q.get(index));
        if !current_item.is_some_and(|item| item.uri() == current_uri) {
            return None;
        }
        let seed_track = station_seed
            .cloned()
            .or_else(|| radio.seed_track.clone())
            .or_else(|| current_item.and_then(Playable::track));
        let seed_key = seed_track
            .as_ref()
            .map(crate::recommendations::engine::song_key)
            .filter(|key| !key.is_empty());

        // Only actual current/future lane entries reserve radio candidates.
        // Parked restored context remains metadata and may be rediscovered.
        let played_indices = self.played_indices.read().unwrap().clone();
        let explicit = self.explicit_queued.read().unwrap().clone();
        let active_radio = self.active_radio.read().unwrap().clone();
        let radio_generated = self.radio_generated.read().unwrap().clone();
        let resume_context = self.resume_context.read().unwrap().clone();
        let resume_context_valid = *self.resume_context_valid.read().unwrap();
        let random_order_ref = random_order.as_ref();
        let mut queued_uris = HashSet::new();
        let mut queued_keys = HashSet::new();
        if let Some(index) = current
            && let Some(item) = q.get(index)
        {
            queued_uris.insert(item.uri());
            if let Some(key) = playable_song_key(item) {
                queued_keys.insert(key);
            }
        }
        let session_played = self.session_played.lock().unwrap().clone();
        let session_song_keys = self.session_song_keys.lock().unwrap().clone();
        let auto_excluded =
            automatic_session_excluded(&q, &radio_generated, &session_played, &session_song_keys);
        for index in self.upcoming_indices_locked(
            usize::MAX,
            current,
            random_order_ref,
            q.len(),
            &played_indices,
            &explicit,
            &active_radio,
            &radio_generated,
            &resume_context,
            resume_context_valid,
            &auto_excluded,
            true,
        ) {
            if let Some(item) = q.get(index) {
                queued_uris.insert(item.uri());
                if let Some(key) = playable_song_key(item) {
                    queued_keys.insert(key);
                }
            }
        }
        let mut batch_uris = HashSet::new();
        let mut batch_keys = HashSet::new();
        let filtered: Vec<_> = tracks
            .iter()
            .filter(|track| {
                let uri = track.uri();
                let key = playable_song_key(track);
                if uri == current_uri
                    || seed_track
                        .as_ref()
                        .is_some_and(|seed| same_track_identity(seed, track))
                    || seed_key
                        .as_ref()
                        .zip(key.as_ref())
                        .is_some_and(|(seed, candidate)| seed == candidate)
                    || session_played.contains(&uri)
                    || key
                        .as_ref()
                        .is_some_and(|key| session_song_keys.contains(key))
                    || queued_uris.contains(&uri)
                    || key.as_ref().is_some_and(|key| queued_keys.contains(key))
                    || !batch_uris.insert(uri)
                    || key
                        .as_ref()
                        .is_some_and(|key| !batch_keys.insert(key.clone()))
                {
                    return false;
                }
                true
            })
            .cloned()
            .collect();
        if filtered.is_empty() {
            return Some(0);
        }

        let first = if after_current {
            match current {
                Some(index) => index + 1,
                None => q.len(),
            }
        } else {
            q.len()
        };
        if let Some(order) = random_order.as_mut() {
            if after_current {
                let insertion_position = current
                    .and_then(|index| order.iter().position(|&item| item == index))
                    .map_or(order.len(), |position| position + 1);
                for index in order.iter_mut() {
                    if *index >= first {
                        *index += filtered.len();
                    }
                }
                order.splice(
                    insertion_position..insertion_position,
                    first..first + filtered.len(),
                );
            } else {
                order.extend(first..first + filtered.len());
            }
        }

        shift_indices_on_insert(
            &mut self.explicit_queued.write().unwrap(),
            first,
            filtered.len(),
        );
        let mut generated = self.radio_generated.write().unwrap();
        let mut active_radio = self.active_radio.write().unwrap();
        if after_current {
            shift_indices_on_insert(&mut generated, first, filtered.len());
            shift_indices_on_insert(&mut active_radio, first, filtered.len());
            shift_indices_on_insert(
                &mut self.played_indices.write().unwrap(),
                first,
                filtered.len(),
            );
            shift_resume_on_insert(
                &mut self.resume_context.write().unwrap(),
                first,
                filtered.len(),
            );
        }
        for (offset, track) in filtered.iter().enumerate() {
            let index = first + offset;
            q.insert(index, track.clone());
            generated.insert(index);
            active_radio.insert(index);
        }
        *generation_guard = generation_guard.wrapping_add(1);
        Some(filtered.len())
    }

    /// Remove the item at `index`. This doesn't take into account shuffle
    /// status, and will literally remove the item at `index` in `self.queue`.
    pub fn remove(&self, index: usize) {
        let mut generation = self.rpc_mutation.lock().unwrap();
        self.remove_inner(index);
        *generation = generation.wrapping_add(1);
    }

    fn remove_inner(&self, index: usize) {
        let (current, len) = {
            // Use the same order as station insertion and shuffle generation.
            let _station = self.radio.lock().unwrap();
            let mut order = self.random_order.write().unwrap();
            let mut items = self.queue.write().unwrap();
            if index >= items.len() {
                return;
            }
            let mut current = self.current_track.write().unwrap();
            let previous = *current;
            items.remove(index);
            shift_indices_on_remove(&mut self.explicit_queued.write().unwrap(), index);
            shift_indices_on_remove(&mut self.radio_generated.write().unwrap(), index);
            shift_indices_on_remove(&mut self.active_radio.write().unwrap(), index);
            shift_indices_on_remove(&mut self.played_indices.write().unwrap(), index);
            shift_resume_on_remove(&mut self.resume_context.write().unwrap(), index);
            if let Some(order) = order.as_mut() {
                order.retain(|item| *item != index);
                for item in order {
                    if *item > index {
                        *item -= 1;
                    }
                }
            }
            match previous {
                Some(position) if position > index => {
                    *current = Some(position - 1);
                }
                Some(position) if position == index => {
                    *current = None;
                    let mut token = self.current_token.write().unwrap();
                    *token = token.wrapping_add(1).max(1);
                }
                _ => {}
            }
            (previous, items.len())
        };
        if len == 0 {
            self.stop();
        } else if current == Some(index) {
            if index < len {
                self.play(index, false, false);
            } else {
                self.stop();
            }
        }
    }

    /// Clear all the items from the queue and stop playback.
    pub fn clear(&self) {
        let mut generation = self.rpc_mutation.lock().unwrap();
        self.clear_inner();
        *generation = generation.wrapping_add(1);
    }

    fn clear_inner(&self) {
        self.stop();

        let mut random_order = self.random_order.write().unwrap();
        let mut q = self.queue.write().unwrap();
        q.clear();
        // A concurrent play may have selected an item after stop but before this write lock.
        // Reset while holding items, matching play's items -> current lock order.
        let had_current = self.current_track.write().unwrap().take().is_some();
        if had_current {
            let mut token = self.current_token.write().unwrap();
            *token = token.wrapping_add(1).max(1);
        }
        if let Some(o) = random_order.as_mut() {
            o.clear()
        }
        self.explicit_queued.write().unwrap().clear();
        self.radio_generated.write().unwrap().clear();
        self.active_radio.write().unwrap().clear();
        self.played_indices.write().unwrap().clear();
        self.resume_context.write().unwrap().clear();
        *self.resume_context_valid.write().unwrap() = false;
    }

    /// Append and select one exact occurrence atomically with other structural edits.
    pub fn rpc_append_play(&self, item: Playable) {
        self.rpc_append_play_many(&[item]);
    }

    /// Append an entire explicit user context without interleaving radio insertions.
    pub fn rpc_append_many(&self, items: &[Playable]) {
        if items.is_empty() {
            return;
        }
        let mut generation = self.rpc_mutation.lock().unwrap();
        for item in items {
            self.append_inner(item.clone());
        }
        *generation = generation.wrapping_add(1);
    }

    /// Append a complete playback context and select its first exact occurrence atomically.
    pub fn rpc_append_play_many(&self, items: &[Playable]) {
        if items.is_empty() {
            return;
        }
        let mut generation = self.rpc_mutation.lock().unwrap();
        // Choosing a fresh playback context is an explicit station escape:
        // discard the parked continuation so this newly selected context owns
        // the next lane. Existing raw items remain retained in the queue.
        self.cancel_radio();
        self.resume_context.write().unwrap().clear();
        *self.resume_context_valid.write().unwrap() = false;
        let index = self.len();
        for item in items {
            self.append_context_inner(item.clone());
        }
        self.play(index, false, false);
        *generation = generation.wrapping_add(1);
    }

    /// Select a radio seed that is outside the current queue while preserving
    /// the station's parked continuation. The station is initialized before
    /// the new occurrence is appended, so capturing the old current position
    /// cannot mistake the newly selected seed for retained context.
    pub fn rpc_append_play_radio_seed(&self, track: &Track) -> u64 {
        let _mutation = self.rpc_mutation.lock().unwrap();
        let current_matches = self
            .get_current()
            .is_some_and(|item| item.uri() == track.uri);
        let generation = self.start_radio_track_locked(track);
        if !current_matches {
            let index = self.len();
            self.append_item_inner(Playable::Track(track.clone()), true);
            self.play(index, false, false);
        }
        generation
    }

    /// A revision identifies one exact structural snapshot, including duplicate occurrences.
    pub fn rpc_snapshot(&self) -> (String, Vec<Playable>, Option<usize>) {
        let generation = self.rpc_mutation.lock().unwrap();
        let items = self.queue.read().unwrap().clone();
        let revision = Self::rpc_revision(*generation, &items);
        (revision, items, self.get_current_index())
    }

    fn rpc_revision(generation: u64, items: &[Playable]) -> String {
        use std::hash::{Hash, Hasher};
        let mut hash = std::collections::hash_map::DefaultHasher::new();
        generation.hash(&mut hash);
        for item in items {
            item.uri().hash(&mut hash);
        }
        format!("{:016x}", hash.finish())
    }

    /// Validate and mutate under the same structural lock used by queue and radio edits.
    pub fn rpc_checked_action(
        &self,
        action: &str,
        revision: &str,
        entry_id: Option<&str>,
        to: Option<usize>,
    ) -> Result<(), String> {
        let mut generation = self.rpc_mutation.lock().unwrap();
        let (current_revision, len) = {
            let items = self.queue.read().unwrap();
            (Self::rpc_revision(*generation, &items), items.len())
        };
        if revision != current_revision {
            return Err("Queue changed; refresh before editing".into());
        }
        let index = if action == "clear" {
            0
        } else {
            let prefix = format!("{revision}:");
            entry_id
                .and_then(|id| id.strip_prefix(&prefix))
                .and_then(|index| index.parse::<usize>().ok())
                .filter(|index| *index < len)
                .ok_or_else(|| "Queue entry no longer exists".to_string())?
        };
        match action {
            "play" => {
                let active = self.radio.lock().unwrap().active;
                let consumed = self.played_indices.read().unwrap().contains(&index);
                let automatic = self.radio_generated.read().unwrap().contains(&index);
                if consumed && (active || automatic) {
                    return Err(
                        "Entry already played this session; append another occurrence to replay"
                            .into(),
                    );
                }
                self.play(index, false, false);
            }
            "remove" => self.remove_inner(index),
            "clear" => self.clear_inner(),
            "move" => {
                let destination = to
                    .filter(|to| *to < len)
                    .ok_or_else(|| "Destination out of bounds".to_string())?;
                self.shift_inner(index, destination);
            }
            _ => return Err("Unsupported queue mutation".into()),
        }
        if action != "play" {
            *generation = generation.wrapping_add(1);
        }
        Ok(())
    }

    /// The amount of items in `self.queue`.
    pub fn len(&self) -> usize {
        self.queue.read().unwrap().len()
    }

    /// Shift the item at `from` in `self.queue` to `to`.
    pub fn shift(&self, from: usize, to: usize) {
        let mut generation = self.rpc_mutation.lock().unwrap();
        self.shift_inner(from, to);
        *generation = generation.wrapping_add(1);
    }

    fn shift_inner(&self, from: usize, to: usize) {
        let mut random_order = self.random_order.write().unwrap();
        let mut queue = self.queue.write().unwrap();
        let item = queue.remove(from);
        queue.insert(to, item);
        if let Some(order) = random_order.as_mut() {
            for index in order {
                if *index == from {
                    *index = to;
                } else if to < from && *index >= to && *index < from {
                    *index += 1;
                } else if from < to && *index > from && *index <= to {
                    *index -= 1;
                }
            }
        }

        shift_indices_on_move(&mut self.explicit_queued.write().unwrap(), from, to);
        shift_indices_on_move(&mut self.radio_generated.write().unwrap(), from, to);
        shift_indices_on_move(&mut self.active_radio.write().unwrap(), from, to);
        shift_indices_on_move(&mut self.played_indices.write().unwrap(), from, to);
        shift_resume_on_move(&mut self.resume_context.write().unwrap(), from, to);

        // if the currently playing track is affected by the shift, update its
        // index
        let mut current = self.current_track.write().unwrap();
        if let Some(index) = *current {
            if index == from {
                current.replace(to);
            } else if to < from && index >= to && index < from {
                current.replace(index + 1);
            } else if from < to && index > from && index <= to {
                current.replace(index - 1);
            }
        }
    }

    /// Play the item at `index` in `self.queue`.
    ///
    /// `reshuffle`: Reshuffle the current order of the queue.
    /// `shuffle_index`: If this is true, `index` isn't actually used, but is
    /// chosen at random as a valid index in the queue.
    pub fn play(&self, mut index: usize, reshuffle: bool, shuffle_index: bool) {
        let queue_length = self.queue.read().unwrap().len();
        // The length of the queue must be bigger than 0 or gen_range panics!
        if queue_length > 0 && shuffle_index && self.get_shuffle() {
            let mut rng = rand::rng();
            index = rng.random_range(0..queue_length);
        }

        self.observe_listening();
        // Choose, mark and advance atomically with station insertion. A worker
        // cannot shift the chosen entry between cloning it and setting current.
        let previous_index = self.get_current_index();
        let track = {
            let mut radio = self.radio.lock().unwrap();
            let items = self.queue.read().unwrap();
            let consumed = self.played_indices.read().unwrap().contains(&index);
            let automatic = self.radio_generated.read().unwrap().contains(&index);
            let session_duplicate = automatic
                && Some(index) != previous_index
                && items.get(index).is_some_and(|item| {
                    self.session_played.lock().unwrap().contains(&item.uri())
                        || playable_song_key(item).is_some_and(|key| {
                            self.session_song_keys.lock().unwrap().contains(&key)
                        })
                });
            if (consumed || session_duplicate) && (radio.active || automatic) {
                crate::ui::osd::notify(
                    "Already played this session; queue the song again to replay it",
                );
                return;
            }
            let track = items.get(index).cloned();
            if let Some(track) = &track {
                self.listening.lock().unwrap().finish(false, false);
                self.mark_session_played_item(track);
                self.played_indices.write().unwrap().insert(index);
                self.resume_context
                    .write()
                    .unwrap()
                    .retain(|pending| *pending != index);
                self.current_track.write().unwrap().replace(index);
                let mut token = self.current_token.write().unwrap();
                *token = token.wrapping_add(1).max(1);
                radio.natural_end = false;
            }
            track
        };
        if let Some(track) = track.as_ref() {
            self.spotify.load(track, true, 0);
            self.listening.lock().unwrap().observe(track.track(), false);
            self.spotify.update_track();

            #[cfg(feature = "notify")]
            if self.cfg.values().notify.unwrap_or(false) {
                std::thread::spawn({
                    // use same parser as track_format, Playable::format
                    let format = self
                        .cfg
                        .values()
                        .notification_format
                        .clone()
                        .unwrap_or_default();
                    let default_title = crate::config::NotificationFormat::default().title.unwrap();
                    let title = format.title.unwrap_or_else(|| default_title.clone());

                    let default_body = crate::config::NotificationFormat::default().body.unwrap();
                    let body = format.body.unwrap_or_else(|| default_body.clone());

                    let summary_txt = Playable::format(track, &title, &self.library);
                    let body_txt = Playable::format(track, &body, &self.library);
                    let cover_url = track.cover_url();
                    move || send_notification(&summary_txt, &body_txt, cover_url)
                });
            }

            // Send a Seeked signal at start of new track
            #[cfg(feature = "mpris")]
            self.spotify.notify_seeked(0);
        }

        if reshuffle && self.get_shuffle() {
            self.generate_random_order()
        }
    }

    /// Toggle the playback. If playback is currently stopped, this will either
    /// play the next song if one is available, or restart from the start.
    pub fn toggleplayback(&self) {
        match self.spotify.get_current_status() {
            PlayerEvent::Playing(_) | PlayerEvent::Paused(_) => {
                self.spotify.toggleplayback();
            }
            PlayerEvent::Stopped => {
                let _mutation = self.rpc_mutation.lock().unwrap();
                if self.get_current_index().is_none() {
                    if let Some((index, _)) = self.upcoming(1).into_iter().next() {
                        self.play(index, false, false);
                    } else {
                        self.play(0, false, false);
                    }
                } else if self.next_index().is_some() {
                    self.next_inner(false);
                } else {
                    self.play(0, false, false);
                }
            }
            _ => (),
        }
    }

    /// Stop playback.
    pub fn stop(&self) {
        self.cancel_radio();
        self.finish_listening();
        let mut current = self.current_track.write().unwrap();
        if current.take().is_some() {
            let mut token = self.current_token.write().unwrap();
            *token = token.wrapping_add(1).max(1);
        }
        self.spotify.stop();
    }

    /// Play the next song in the queue. Stops playback if there are no playable tracks
    /// remaining.
    ///
    /// `manual`: If this is true, normal queue logic like repeat will not be
    /// used, and the next track will actually be played. This should be used
    /// when going to the next entry in the queue is the wanted behavior.
    pub fn next(&self, manual: bool) {
        let _mutation = self.rpc_mutation.lock().unwrap();
        self.next_inner(manual);
    }

    fn next_inner(&self, manual: bool) {
        self.observe_listening();
        let finished = self.spotify.get_current_status() == PlayerEvent::FinishedTrack;
        self.listening.lock().unwrap().finish(manual, finished);
        let current = *self.current_track.read().unwrap();
        let repeat = self.cfg.state().repeat;
        // Read what this needs out of the queue and drop the guard before going on:
        // `next_index` and `play` take the same lock again, and a recursive read
        // deadlocks whenever a writer on another thread is already queued behind us.
        let (current_playable, any_playable) = {
            let q = self.queue.read().unwrap();
            (
                current.is_some_and(|index| q.get(index).is_some_and(|track| track.is_playable())),
                q.iter().any(|track| track.is_playable()),
            )
        };

        let current_is_radio = current.is_some_and(|index| self.is_radio_generated(index));
        if repeat == RepeatSetting::RepeatTrack
            && !manual
            && !current_is_radio
            && !self.radio_active()
        {
            if let Some(index) = current
                && current_playable
            {
                self.play(index, false, false);
            }
        } else if let Some(index) = self.next_index() {
            self.play(index, false, false);
            if repeat == RepeatSetting::RepeatTrack && manual {
                self.set_repeat(RepeatSetting::RepeatPlaylist);
            }
        } else if repeat == RepeatSetting::RepeatPlaylist && any_playable {
            if let Some(first) = self.repeatable_index(false) {
                self.play(first, false, false);
            } else {
                // An active station may still be waiting for metadata. Keep the
                // radio generation alive so its worker can refill later, while
                // avoiding a repeat loop over autogenerated entries.
                self.wait_for_radio_or_stop();
            }
        } else {
            self.wait_for_radio_or_stop();
        }
    }

    /// Play the previous item in the queue.
    pub fn previous(&self) {
        let _mutation = self.rpc_mutation.lock().unwrap();
        let current = *self.current_track.read().unwrap();
        let repeat = self.cfg.state().repeat;
        // As in `next`: take the length and release the lock, so the `play` call
        // below is not a recursive read on `self.queue`.
        let length = self.queue.read().unwrap().len();

        if let Some(index) = self.previous_index() {
            self.play(index, false, false);
        } else if repeat == RepeatSetting::RepeatPlaylist && length > 0 {
            if let Some(last) = self.repeatable_index(true) {
                self.play(last, false, false);
            }
        } else if let Some(index) = current {
            self.play(index, false, false);
        }
    }

    /// Get the current repeat behavior.
    pub fn get_repeat(&self) -> RepeatSetting {
        self.cfg.state().repeat
    }

    /// Find a manual queue item for repeat-playlist wrapping. Autogenerated
    /// radio items are intentionally skipped so repeat settings cannot replay a
    /// station item after the station has advanced.
    fn repeatable_index(&self, reverse: bool) -> Option<usize> {
        let radio_active = self.radio.lock().unwrap().active;
        let random_order = self.random_order.read().unwrap();
        let queue = self.queue.read().unwrap();
        let generated = self.radio_generated.read().unwrap();
        let explicit = self.explicit_queued.read().unwrap();
        let active_radio = self.active_radio.read().unwrap();
        let played = self.played_indices.read().unwrap();
        let session_played = self.session_played.lock().unwrap();
        let session_song_keys = self.session_song_keys.lock().unwrap();
        let auto_excluded =
            automatic_session_excluded(&queue, &generated, &session_played, &session_song_keys);
        let indices: Vec<usize> = match random_order.as_ref() {
            Some(order) if reverse => order.iter().rev().copied().collect(),
            Some(order) => order.clone(),
            None if reverse => (0..queue.len()).rev().collect(),
            None => (0..queue.len()).collect(),
        };
        indices.into_iter().find(|index| {
            queue.get(*index).is_some_and(|track| {
                track.is_playable()
                    && if radio_active {
                        (explicit.contains(index) || active_radio.contains(index))
                            && !played.contains(index)
                            && (!active_radio.contains(index) || !auto_excluded.contains(index))
                    } else {
                        !generated.contains(index)
                    }
            })
        })
    }

    /// Set the current repeat behavior and save it to the configuration.
    pub fn set_repeat(&self, new: RepeatSetting) {
        self.cfg.with_state_mut(|s| s.repeat = new);
    }

    /// Get the current shuffle behavior.
    pub fn get_shuffle(&self) -> bool {
        self.cfg.state().shuffle
    }

    /// Get the current order that is used to shuffle.
    pub fn get_random_order(&self) -> Option<Vec<usize>> {
        self.random_order.read().unwrap().clone()
    }

    /// (Re)generate the random shuffle order.
    fn generate_random_order(&self) {
        let mut random_order = self.random_order.write().unwrap();
        let q = self.queue.read().unwrap();
        let mut order: Vec<usize> = Vec::with_capacity(q.len());
        let mut random: Vec<usize> = (0..q.len()).collect();

        if let Some(current) =
            (*self.current_track.read().unwrap()).filter(|current| *current < q.len())
        {
            order.push(current);
            random.remove(current);
        }

        let mut rng = rand::rng();
        random.shuffle(&mut rng);
        order.extend(random);

        *random_order = Some(order);
    }

    /// Set the current shuffle behavior.
    pub fn set_shuffle(&self, new: bool) {
        self.cfg.with_state_mut(|s| s.shuffle = new);
        if new {
            self.generate_random_order();
        } else {
            let mut random_order = self.random_order.write().unwrap();
            *random_order = None;
        }
    }

    /// Handle events that are specific to the queue.
    pub fn handle_event(&self, event: QueueEvent) {
        match event {
            QueueEvent::PreloadTrackRequest => {
                if let Some(next_index) = self.next_index() {
                    self.preload_at(next_index);
                }
            }
        }
    }

    /// The candidate index may become stale while an RPC removes or clears entries.
    fn preload_at(&self, index: usize) {
        let track = self.queue.read().unwrap().get(index).cloned();
        if let Some(track) = track {
            debug!("Preloading track {track} as requested by librespot");
            self.spotify.preload(&track);
        }
    }

    /// Get the spotify session.
