/// Repeat behavior for the [Queue].
#[derive(Display, Clone, Copy, PartialEq, Eq, Debug, Serialize, Deserialize)]
pub enum RepeatSetting {
    #[serde(rename = "off")]
    None,
    #[serde(rename = "playlist")]
    RepeatPlaylist,
    #[serde(rename = "track")]
    RepeatTrack,
}

/// Events that are specific to the [Queue].
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum QueueEvent {
    /// Request the player to 'preload' a track, basically making sure that
    /// transitions between tracks can be uninterrupted.
    PreloadTrackRequest,
}

/// The queue determines the playback order of [Playable] items, and is also used to control
/// playback itself.
pub struct Queue {
    /// The internal data, which doesn't change with shuffle or repeat. This is
    /// the raw data only.
    pub queue: Arc<RwLock<Vec<Playable>>>,
    rpc_mutation: Mutex<u64>,
    /// The playback order of the queue, as indices into `self.queue`.
    random_order: RwLock<Option<Vec<usize>>>,
    current_track: RwLock<Option<usize>>,
    spotify: Spotify,
    cfg: Arc<Config>,
    library: Arc<Library>,
    listening: Mutex<crate::recommendations::tracker::Tracker>,
    /// URIs observed in this process. This intentionally survives queue edits so a
    /// local radio station cannot reintroduce a track after it has been removed.
    session_played: Mutex<HashSet<String>>,
    /// Song identities observed in this process. Unlike URI history this keeps
    /// alternate Spotify releases of one song from re-entering radio.
    session_song_keys: Mutex<HashSet<String>>,
    /// Raw queue indices explicitly selected by the user. Indices are adjusted
    /// alongside queue edits so a duplicate occurrence remains independently
    /// eligible for playback.
    explicit_queued: RwLock<HashSet<usize>>,
    /// Every raw queue index generated by local radio, including older stations.
    /// This is provenance that is persisted with the queue.
    radio_generated: RwLock<HashSet<usize>>,
    /// Raw queue indices generated by the currently active station generation.
    /// Older radio entries remain in the raw queue but are parked while a station
    /// is active and become ordinary retained context after cancellation.
    active_radio: RwLock<HashSet<usize>>,
    /// Queue entries already selected for playback in this terminal session.
    /// This preserves per-entry identity so a newly queued duplicate remains an
    /// explicit user choice even when its URI was played earlier.
    played_indices: RwLock<HashSet<usize>>,
    /// Monotonic identity for the exact current queue occurrence. This rejects
    /// delayed radio fills after remove/reinsert ABA at the same raw index.
    current_token: RwLock<u64>,
    /// Future raw entries parked when a station starts. Radio batches are
    /// appended after that context, so this continuation keeps those entries
    /// reachable if playback advances past them before the station is stopped.
    resume_context: RwLock<Vec<usize>>,
    /// Distinguishes an intentionally empty captured continuation from a
    /// station that has never owned the queue lane.
    resume_context_valid: RwLock<bool>,
    radio: Mutex<RadioState>,
}

/// State shared by radio workers and the UI thread. Holding this lock while a
/// radio batch is applied makes cancellation/generation checks atomic with the
/// queue insertion.
#[derive(Default)]
struct RadioState {
    generation: u64,
    active: bool,
    seed: Option<String>,
    seed_track: Option<Track>,
    in_flight: bool,
    retry_at: Option<Instant>,
    retry_attempt: u8,
    waiting: bool,
    natural_end: bool,
    refresh_requested: bool,
}

const RADIO_RETRY_BASE: Duration = Duration::from_secs(1);
const RADIO_RETRY_MAX: Duration = Duration::from_secs(60);

/// A single-flight radio request is tied to the exact queue occurrence that was
/// current when it was claimed. The original station seed is carried separately
/// so refills remain anchored even after playback advances through the queue.
#[derive(Clone, Debug)]
pub(crate) struct RadioFill {
    pub(crate) generation: u64,
    pub(crate) seed: Track,
    pub(crate) current_index: usize,
    pub(crate) current_uri: String,
    pub(crate) current_token: u64,
}

fn shift_indices_on_insert(indices: &mut HashSet<usize>, first: usize, count: usize) {
    if count == 0 {
        return;
    }
    let shifted: HashSet<_> = indices
        .iter()
        .copied()
        .map(|index| if index >= first { index + count } else { index })
        .collect();
    *indices = shifted;
}

fn shift_indices_on_remove(indices: &mut HashSet<usize>, removed: usize) {
    let existing: Vec<_> = indices.iter().copied().collect();
    indices.clear();
    for index in existing {
        if index < removed {
            indices.insert(index);
        } else if index > removed {
            indices.insert(index - 1);
        }
    }
}

fn shift_indices_on_move(indices: &mut HashSet<usize>, from: usize, to: usize) {
    if from == to {
        return;
    }
    let moved: HashSet<_> = indices
        .iter()
        .copied()
        .map(|index| {
            if index == from {
                to
            } else if from < to && index > from && index <= to {
                index - 1
            } else if to < from && index >= to && index < from {
                index + 1
            } else {
                index
            }
        })
        .collect();
    *indices = moved;
}

fn shift_resume_on_insert(indices: &mut Vec<usize>, first: usize, count: usize) {
    if count == 0 {
        return;
    }
    for index in indices {
        if *index >= first {
            *index += count;
        }
    }
}

fn shift_resume_on_remove(indices: &mut Vec<usize>, removed: usize) {
    indices.retain(|index| *index != removed);
    for index in indices {
        if *index > removed {
            *index -= 1;
        }
    }
}

fn shift_resume_on_move(indices: &mut Vec<usize>, from: usize, to: usize) {
    if from == to {
        return;
    }
    for index in indices {
        if *index == from {
            *index = to;
        } else if from < to && *index > from && *index <= to {
            *index -= 1;
        } else if to < from && *index >= to && *index < from {
            *index += 1;
        }
    }
}

fn playable_song_key(item: &Playable) -> Option<String> {
    let track = item.track()?;
    let key = crate::recommendations::engine::song_key(&track);
    (!key.is_empty()).then_some(key)
}

fn same_track_identity(left: &Track, right: &Playable) -> bool {
    let Some(right) = right.track() else {
        return false;
    };
    left.uri == right.uri
        || left
            .id
            .as_ref()
            .zip(right.id.as_ref())
            .is_some_and(|(left_id, right_id)| !left_id.is_empty() && left_id == right_id)
}

fn automatic_session_excluded(
    queue: &[Playable],
    radio_generated: &HashSet<usize>,
    session_played: &HashSet<String>,
    session_song_keys: &HashSet<String>,
) -> HashSet<usize> {
    radio_generated
        .iter()
        .copied()
        .filter(|index| {
            queue.get(*index).is_some_and(|item| {
                session_played.contains(&item.uri())
                    || playable_song_key(item).is_some_and(|key| session_song_keys.contains(&key))
            })
        })
        .collect()
}

